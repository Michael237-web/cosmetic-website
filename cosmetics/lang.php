/* ---------------------------------------------------------
   3. Get a translated string
   --------------------------------------------------------- */
function t(string $key, ?string $fallback = null): string {
    $lang = current_lang();
    $dict = translations();
    return $dict[$lang][$key]
        ?? $dict['en'][$key]
        ?? $fallback
        ?? $key;
}

