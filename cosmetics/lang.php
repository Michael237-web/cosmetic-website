/* ---------------------------------------------------------
   1. Detect current language
   --------------------------------------------------------- */
function supported_langs(): array {
    return ['en','sw','fr','es','zh','ar','de'];
}

function current_lang(): string {
    if (session_status() !== PHP_SESSION_ACTIVE) session_start();

    $allowed = supported_langs();

    if (!empty($_GET['lang']) && in_array($_GET['lang'], $allowed, true)) {
        $_SESSION['lang'] = $_GET['lang'];
        setcookie('lang', $_GET['lang'], time() + 60*60*24*365, '/');

        $url = strtok($_SERVER['REQUEST_URI'], '?');
        $query = $_GET;
        unset($query['lang']);
        if (!empty($query)) {
            $url .= '?' . http_build_query($query);
        }
        header('Location: ' . $url);
        exit;
    }

    if (!empty($_SESSION['lang']) && in_array($_SESSION['lang'], $allowed, true)) {
        return $_SESSION['lang'];
    }
    if (!empty($_COOKIE['lang']) && in_array($_COOKIE['lang'], $allowed, true)) {
        return $_COOKIE['lang'];
    }
    return 'en';
}

function is_rtl(): bool {
    return current_lang() === 'ar';
}

